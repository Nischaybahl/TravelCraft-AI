import jsPDF from 'jspdf';
import 'jspdf-autotable';
import type { Trip } from '@/types';
import { formatCurrency, formatDate } from './formatters';

declare module 'jspdf' {
  interface jsPDF {
    autoTable: (options: unknown) => jsPDF;
    lastAutoTable: { finalY: number };
  }
}

export function exportTripToPDF(trip: Trip): void {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(30, 58, 95); // navy
  doc.rect(0, 0, pageWidth, 40, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('TravelCraft AI', 14, 18);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('Your Intelligent Travel Companion', 14, 26);

  doc.setFontSize(14);
  doc.text(trip.title, 14, 36);

  // Trip Summary
  doc.setTextColor(30, 58, 95);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Trip Overview', 14, 55);

  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(60, 60, 60);

  const summaryData = [
    ['Destination', `${trip.destination}, ${trip.country}`],
    ['Dates', `${formatDate(trip.start_date)} — ${formatDate(trip.end_date)}`],
    ['Duration', `${trip.duration_days} days`],
    ['Travelers', `${trip.num_travelers}`],
    ['Style', `${trip.travel_style} / ${trip.travel_pace}`],
    ['Budget', formatCurrency(trip.budget, trip.currency)],
    ['Estimated Cost', formatCurrency(trip.total_estimated_cost, trip.currency)],
  ];

  doc.autoTable({
    startY: 60,
    head: [],
    body: summaryData,
    theme: 'plain',
    styles: { fontSize: 10, cellPadding: 3 },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 45, textColor: [30, 58, 95] },
      1: { textColor: [60, 60, 60] },
    },
  });

  // Itinerary
  if (trip.itinerary && trip.itinerary.length > 0) {
    let currentY = doc.lastAutoTable.finalY + 15;

    trip.itinerary.forEach((day) => {
      if (currentY > 250) {
        doc.addPage();
        currentY = 20;
      }

      doc.setTextColor(79, 70, 229); // indigo
      doc.setFontSize(13);
      doc.setFont('helvetica', 'bold');
      doc.text(`Day ${day.day_number}: ${day.theme}`, 14, currentY);
      currentY += 5;

      doc.setFontSize(9);
      doc.setFont('helvetica', 'italic');
      doc.setTextColor(100, 100, 100);
      doc.text(`${formatDate(day.date)} — ${day.summary}`, 14, currentY);
      currentY += 5;

      if (day.activities && day.activities.length > 0) {
        const activityRows = day.activities.map((act) => [
          act.suggested_time || act.time_slot,
          act.name,
          act.location || '-',
          act.estimated_duration,
          formatCurrency(act.approximate_cost, trip.currency),
        ]);

        doc.autoTable({
          startY: currentY,
          head: [['Time', 'Activity', 'Location', 'Duration', 'Cost']],
          body: activityRows,
          theme: 'striped',
          headStyles: { fillColor: [30, 58, 95], fontSize: 8 },
          styles: { fontSize: 8, cellPadding: 2 },
        });

        currentY = doc.lastAutoTable.finalY + 8;
      }

      // Day tips
      if (day.travel_tips) {
        if (currentY > 270) {
          doc.addPage();
          currentY = 20;
        }
        doc.setFontSize(8);
        doc.setFont('helvetica', 'italic');
        doc.setTextColor(13, 148, 136); // teal
        doc.text(`💡 Tips: ${day.travel_tips}`, 14, currentY, { maxWidth: pageWidth - 28 });
        currentY += 10;
      }
    });
  }

  // Footer on last page
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text(
      `Generated by TravelCraft AI — Page ${i} of ${pageCount}`,
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 10,
      { align: 'center' }
    );
  }

  doc.save(`${trip.title.replace(/\s+/g, '_')}_itinerary.pdf`);
}

export function exportTripToJSON(trip: Trip): void {
  const json = JSON.stringify(trip, null, 2);
  const blob = new Blob([json], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${trip.title.replace(/\s+/g, '_')}_itinerary.json`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function importTripFromJSON(file: File): Promise<Trip> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      try {
        const trip = JSON.parse(e.target?.result as string) as Trip;
        if (!trip.title || !trip.destination) {
          reject(new Error('Invalid trip data'));
          return;
        }
        resolve(trip);
      } catch {
        reject(new Error('Invalid JSON file'));
      }
    };
    reader.onerror = () => reject(new Error('Failed to read file'));
    reader.readAsText(file);
  });
}
