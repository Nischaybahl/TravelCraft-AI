"""
TravelCraft AI - PDF Export Service

Generates downloadable PDF itineraries using fpdf2.
"""

from __future__ import annotations

import logging
from typing import List

from fpdf import FPDF

logger = logging.getLogger(__name__)


class TravelPDF(FPDF):
    """Custom PDF with headers and footers."""

    def __init__(self, title: str = "TravelCraft AI Itinerary"):
        super().__init__()
        self._doc_title = title
        self.set_auto_page_break(auto=True, margin=20)

    def header(self):
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(30, 58, 95)
        self.cell(0, 8, self._doc_title, align="L")
        self.ln(10)
        self.set_draw_color(30, 58, 95)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f"Page {self.page_no()}/{{nb}} | Generated by TravelCraft AI", align="C")


def _safe_text(text) -> str:
    """Convert to string and handle encoding."""
    if text is None:
        return ""
    return str(text).encode("latin-1", "replace").decode("latin-1")


def generate_pdf(trip_data: dict, itinerary_days: list) -> bytes:
    """Generate a complete PDF itinerary document."""
    destination = trip_data.get("destination", "Unknown")
    title = trip_data.get("title", f"Trip to {destination}")

    pdf = TravelPDF(title=_safe_text(title))
    pdf.alias_nb_pages()
    pdf.add_page()

    # ---- Cover / Title ----
    pdf.set_font("Helvetica", "B", 24)
    pdf.set_text_color(30, 58, 95)
    pdf.ln(20)
    pdf.cell(0, 15, _safe_text(title), align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 14)
    pdf.set_text_color(79, 70, 229)
    pdf.cell(0, 10, "Your Intelligent Travel Companion", align="C", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(15)

    # ---- Trip Summary ----
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 58, 95)
    pdf.cell(0, 10, "Trip Summary", new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(79, 70, 229)
    pdf.line(10, pdf.get_y(), 80, pdf.get_y())
    pdf.ln(5)

    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(50, 50, 50)

    summary_items = [
        ("Destination", f"{destination}, {trip_data.get('country', '')}"),
        ("Dates", f"{trip_data.get('start_date', '')} to {trip_data.get('end_date', '')}"),
        ("Duration", f"{trip_data.get('duration_days', '')} days"),
        ("Travelers", f"{trip_data.get('num_travelers', 1)}"),
        ("Budget", f"{trip_data.get('budget', 0)} {trip_data.get('currency', 'USD')}"),
        ("Travel Style", str(trip_data.get('travel_style', 'moderate')).capitalize()),
        ("Travel Pace", str(trip_data.get('travel_pace', 'balanced')).capitalize()),
        ("Travel Group", str(trip_data.get('travel_group', 'solo')).capitalize()),
    ]

    interests = trip_data.get("interests", [])
    if interests:
        summary_items.append(("Interests", ", ".join(interests)))

    dietary = trip_data.get("dietary_preferences", [])
    if dietary:
        summary_items.append(("Dietary", ", ".join(dietary)))

    for label, value in summary_items:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(45, 7, _safe_text(f"{label}:"))
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 7, _safe_text(value), new_x="LMARGIN", new_y="NEXT")

    pdf.ln(10)

    # ---- Day-by-Day Itinerary ----
    for day_data in itinerary_days:
        # Handle both dict and Pydantic model
        if hasattr(day_data, "model_dump"):
            day = day_data.model_dump()
        elif isinstance(day_data, dict):
            day = day_data
        else:
            continue

        pdf.add_page()
        day_num = day.get("day_number", "?")
        date = day.get("date", "")
        theme = day.get("theme", "")

        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(30, 58, 95)
        pdf.cell(0, 12, _safe_text(f"Day {day_num}: {theme}"), new_x="LMARGIN", new_y="NEXT")

        if date:
            pdf.set_font("Helvetica", "I", 10)
            pdf.set_text_color(100, 100, 100)
            pdf.cell(0, 6, _safe_text(f"Date: {date}"), new_x="LMARGIN", new_y="NEXT")

        summary = day.get("summary", "")
        if summary:
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(70, 70, 70)
            pdf.multi_cell(0, 5, _safe_text(summary))
        pdf.ln(5)

        # Activities
        activities = day.get("activities", [])
        for act in activities:
            if isinstance(act, dict):
                a = act
            elif hasattr(act, "model_dump"):
                a = act.model_dump()
            else:
                continue

            name = a.get("name", "")
            time_str = a.get("suggested_time", "")
            duration = a.get("estimated_duration", "")
            location = a.get("location", "")
            cost = a.get("approximate_cost", 0)
            desc = a.get("description", "")
            category = a.get("category", "")
            transport = a.get("transport_suggestion", "")

            # Activity header
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(79, 70, 229)
            header_text = f"{time_str}  {name}" if time_str else name
            pdf.cell(0, 7, _safe_text(header_text), new_x="LMARGIN", new_y="NEXT")

            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(70, 70, 70)

            if desc:
                pdf.multi_cell(0, 4.5, _safe_text(desc))

            details = []
            if duration:
                details.append(f"Duration: {duration}")
            if location:
                details.append(f"Location: {location}")
            if category:
                details.append(f"Category: {category}")
            if cost > 0:
                details.append(f"Est. Cost: {trip_data.get('currency', 'USD')} {cost:.2f}")
            if transport:
                details.append(f"Getting there: {transport}")

            if details:
                pdf.set_font("Helvetica", "", 8)
                pdf.set_text_color(100, 100, 100)
                pdf.cell(0, 5, _safe_text(" | ".join(details)), new_x="LMARGIN", new_y="NEXT")

            pdf.ln(3)

        # Day costs
        pdf.ln(3)
        pdf.set_draw_color(200, 200, 200)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(3)

        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(30, 58, 95)
        currency = trip_data.get("currency", "USD")
        costs = [
            f"Activities: {currency} {day.get('activity_cost', 0):.2f}",
            f"Food: {currency} {day.get('food_cost', 0):.2f}",
            f"Transport: {currency} {day.get('transport_cost', 0):.2f}",
            f"Total: {currency} {day.get('estimated_cost', 0):.2f}",
        ]
        pdf.cell(0, 7, _safe_text("Daily Cost Estimate: " + " | ".join(costs)), new_x="LMARGIN", new_y="NEXT")

        # Accommodation
        accommodation = day.get("accommodation_suggestion", "")
        if accommodation:
            pdf.set_font("Helvetica", "I", 9)
            pdf.set_text_color(70, 70, 70)
            pdf.cell(0, 6, _safe_text(f"Accommodation: {accommodation}"), new_x="LMARGIN", new_y="NEXT")

        # Tips
        tips = day.get("travel_tips", "")
        if tips:
            pdf.set_font("Helvetica", "I", 9)
            pdf.set_text_color(13, 148, 136)
            pdf.multi_cell(0, 5, _safe_text(f"Tip: {tips}"))

    # ---- Budget Breakdown ----
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(30, 58, 95)
    pdf.cell(0, 12, "Budget Breakdown", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    currency = trip_data.get("currency", "USD")
    total_budget = float(trip_data.get("budget", 0))
    total_food = sum(d.get("food_cost", 0) if isinstance(d, dict) else getattr(d, "food_cost", 0) for d in itinerary_days)
    total_transport = sum(d.get("transport_cost", 0) if isinstance(d, dict) else getattr(d, "transport_cost", 0) for d in itinerary_days)
    total_activity = sum(d.get("activity_cost", 0) if isinstance(d, dict) else getattr(d, "activity_cost", 0) for d in itinerary_days)
    total_estimated = round(total_food + total_transport + total_activity, 2)
    remaining = round(total_budget - total_estimated, 2)

    budget_items = [
        ("Total Budget", f"{currency} {total_budget:.2f}"),
        ("Estimated Food Costs", f"{currency} {total_food:.2f}"),
        ("Estimated Transport Costs", f"{currency} {total_transport:.2f}"),
        ("Estimated Activity Costs", f"{currency} {total_activity:.2f}"),
        ("Total Estimated Cost", f"{currency} {total_estimated:.2f}"),
        ("Remaining Budget", f"{currency} {remaining:.2f}"),
    ]

    for label, value in budget_items:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(80, 8, _safe_text(label))
        pdf.set_font("Helvetica", "", 11)
        if "Remaining" in label and remaining < 0:
            pdf.set_text_color(220, 38, 38)
        else:
            pdf.set_text_color(50, 50, 50)
        pdf.cell(0, 8, _safe_text(value), new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(50, 50, 50)

    if remaining < 0:
        pdf.ln(5)
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_text_color(220, 38, 38)
        pdf.cell(0, 8, "WARNING: Estimated costs exceed your budget!", new_x="LMARGIN", new_y="NEXT")

    # ---- Travel Checklist ----
    pdf.ln(10)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 58, 95)
    pdf.cell(0, 10, "Travel Checklist", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    checklist = [
        "Passport / ID (check expiry date)",
        "Visa (if required)",
        "Travel insurance documents",
        "Flight / transport tickets",
        "Hotel reservation confirmations",
        "Local currency / travel card",
        "Phone charger and adapter",
        "Copies of important documents",
        "Prescribed medications",
        "Comfortable walking shoes",
        "Weather-appropriate clothing",
        "Camera / phone for photos",
        "Reusable water bottle",
        "Guidebook or offline maps",
    ]

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(50, 50, 50)
    for item in checklist:
        pdf.cell(6, 6, "[ ]")
        pdf.cell(0, 6, _safe_text(f"  {item}"), new_x="LMARGIN", new_y="NEXT")

    # ---- Emergency Preparation ----
    pdf.ln(8)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 58, 95)
    pdf.cell(0, 10, "Emergency Preparation", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)

    emergency = [
        "Save embassy/consulate contact for your destination",
        "Note local emergency numbers (police, ambulance, fire)",
        "Share your itinerary with family or friends",
        "Keep digital and physical copies of your passport",
        "Note your hotel address in the local language",
        "Research nearest hospital / clinic",
        "Set up international calling on your phone",
        "Register with your country's travel advisory service",
        "Carry a basic first aid kit",
        "Know your travel insurance emergency number",
    ]

    pdf.set_font("Helvetica", "", 10)
    for item in emergency:
        pdf.cell(6, 6, "[ ]")
        pdf.cell(0, 6, _safe_text(f"  {item}"), new_x="LMARGIN", new_y="NEXT")

    # ---- Disclaimer ----
    pdf.ln(10)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(150, 150, 150)
    pdf.multi_cell(0, 4, _safe_text(
        "Disclaimer: All costs are approximate estimates and may vary. "
        "Prices, opening hours, and availability are subject to change. "
        "This itinerary was generated by TravelCraft AI and should be "
        "verified before travel. Always check official sources for the "
        "latest information."
    ))

    out = pdf.output()
    if isinstance(out, bytearray):
        return bytes(out)
    return out
